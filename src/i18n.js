function normalizeLanguage(lang) {
  return lang && translations[lang] ? lang : 'en';
}

export function getCurrentLanguage() {
  const stored = localStorage.getItem('mla-lang');
  if (stored && translations[stored]) return stored;
  const browser = navigator.language || 'en';
  if (browser.startsWith('fr')) return 'fr';
  if (browser.startsWith('vi')) return 'vi';
  if (browser.startsWith('zh')) return 'zh';
  if (browser.startsWith('ru')) return 'ru';
  return 'en';
}

export function setLanguage(lang) {
  const normalized = normalizeLanguage(lang);
  localStorage.setItem('mla-lang', normalized);
  document.documentElement.lang = normalized;
  document.body.dataset.lang = normalized;
  return normalized;
}

export function t(key, lang = getCurrentLanguage()) {
  const normalized = normalizeLanguage(lang);
  return translations[normalized][key] || translations.en[key] || key;
}

export function translateValue(value, lang = getCurrentLanguage()) {
  const normalized = normalizeLanguage(lang);
  if (!value) return value;
  return valueTranslations[normalized][value] || valueTranslations.en[value] || value;
}

